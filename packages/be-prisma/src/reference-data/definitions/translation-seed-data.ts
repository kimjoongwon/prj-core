export const translationSeedData: TranslationSeedData[] =
	uniqueTranslationDefinitions(translationDefinitions).flatMap((definition) =>
		LANGUAGE_CODES.map((languageCode) => ({
			languageCode,
			key: definition.key,
			text: definition.texts[languageCode],
			category: definition.category,
			isTranslated: true,
		})),
	);

function uniqueTranslationDefinitions(
	definitions: readonly TranslationDefinition[],
): TranslationDefinition[] {
	const definitionsByKey = new Map<string, TranslationDefinition>();

	for (const definition of definitions) {
		definitionsByKey.set(definition.key, definition);
	}

	return Array.from(definitionsByKey.values());
}

function defineTranslation(
	key: string,
	category: string,
	texts: Record<LanguageCode, string>,
): TranslationDefinition {
	return { key, category, texts };
}

function defineUiTranslations(
	entries: ReadonlyArray<readonly [string, string, string, string]>,
): TranslationDefinition[] {
	return entries.map(([key, en_US, zh_CN, ja_JP]) =>
		defineTranslation(key, "UI", {
			ko_KR: key,
			en_US,
			zh_CN,
			ja_JP,
		}),
	);
}
