import type { TemplateVariable as TemplateVariableEntity } from "@cocrepo/prisma";
import type { Template } from "./template.entity";

export class TemplateVariable implements TemplateVariableEntity {
	// ============================================================================
	// 기본 필드
	// ============================================================================

	id!: string;
	createdAt!: Date;
	updatedAt!: Date | null;

	// ============================================================================
	// 필수 필드
	// ============================================================================

	/** 변수명 */
	name!: string;
	/** 필수 여부 */
	isRequired!: boolean;
	/** 템플릿 ID */
	templateId!: string;

	// ============================================================================
	// Nullable 필드
	// ============================================================================

	/** 변수 설명 */
	description!: string | null;
	/** 기본값 */
	defaultValue!: string | null;

	// ============================================================================
	// 관계 필드 (선택적)
	// ============================================================================

	/** 소속 템플릿 */
	template?: Template;

	// ============================================================================
	// 도메인 메서드
	// ============================================================================

	/**
	 * 기본값이 설정되어 있는지 확인합니다
	 */
	hasDefaultValue(): boolean {
		return this.defaultValue !== null && this.defaultValue.length > 0;
	}

	/**
	 * 플레이스홀더 형태로 반환합니다
	 * 예: "name" -> "{{name}}"
	 */
	toPlaceholder(): string {
		return `{{${this.name}}}`;
	}
}
