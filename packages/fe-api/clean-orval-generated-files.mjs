import { readdir, readFile, unlink } from "node:fs/promises";

const GENERATED_FILE_HEADER = /^\/\*\*\r?\n \* Generated by [Oo]rval/;
const generatedSourceRoot = new URL("./src/core/", import.meta.url);

const collectTypeScriptFiles = async (directoryUrl) => {
	const directoryEntries = await readdir(directoryUrl, { withFileTypes: true });
	const nestedTypeScriptFiles = await Promise.all(
		directoryEntries.map(async (directoryEntry) => {
			const entryUrl = new URL(directoryEntry.name, directoryUrl);
			if (directoryEntry.isDirectory()) {
				return collectTypeScriptFiles(
					new URL(`${directoryEntry.name}/`, directoryUrl),
				);
			}
			return directoryEntry.isFile() && directoryEntry.name.endsWith(".ts")
				? [entryUrl]
				: [];
		}),
	);

	return nestedTypeScriptFiles.flat();
};

const generatedTypeScriptFiles =
	await collectTypeScriptFiles(generatedSourceRoot);
const removedGeneratedFiles = [];

for (const generatedTypeScriptFile of generatedTypeScriptFiles) {
	const sourceHeader = (await readFile(generatedTypeScriptFile, "utf8")).slice(
		0,
		1024,
	);
	if (!GENERATED_FILE_HEADER.test(sourceHeader)) continue;
	await unlink(generatedTypeScriptFile);
	removedGeneratedFiles.push(generatedTypeScriptFile);
}

console.log(
	`Orval 생성 파일 ${removedGeneratedFiles.length}개를 정리했습니다.`,
);
