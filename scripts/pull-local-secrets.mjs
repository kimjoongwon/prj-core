#!/usr/bin/env node
// 로컬 개발 시크릿 OpenBao pull 스크립트
//
// 팀 OpenBao의 development KV v2 경로에서 로컬 개발용 시크릿(이메일 SMTP,
// 객체 스토리지, 인증 서명)을 읽어와 각 앱의 gitignored .env 파일에 병합한다.
// 매핑된 키만 교체하고 나머지 키·로컬 수정값은 보존하며, 시크릿 값은
// 절대 콘솔에 출력하지 않는다.
//
// 사용법:
//   pnpm secrets:pull            # 정책 경로에서 읽어 .env 병합
//   pnpm secrets:pull --dry-run  # 변경될 키 목록만 출력
//   node scripts/pull-local-secrets.mjs --quiet  # start.sh/wt.js 통합용
//
// 인증: VAULT_TOKEN 환경변수 또는 `vault login`이 저장한 ~/.vault-token.
// 주소: VAULT_ADDR 환경변수로 지정 가능. 미지정 시 localhost:8200에 응답하는
// OpenBao가 있으면 사용하고, 없으면 kubectl port-forward로 팀 클러스터의
// OpenBao에 터널을 자동으로 연다 (openbao.onjitda.com은 Cloudflare Access
// 뒤에 있어 CLI 직접 접근이 불가하므로 port-forward가 기본 개발 경로).

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawn, spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const LOCAL_OPENBAO_ADDRESS = "http://127.0.0.1:8200";
const REMOTE_OPENBAO_ADDRESS_FALLBACK = "https://openbao.onjitda.com";
const OPENBAO_KV_MOUNT = "secret";
const OPENBAO_TUNNEL_NAMESPACE = "openbao";
const OPENBAO_TUNNEL_TARGET = "svc/openbao";
const OPENBAO_TUNNEL_READY_TIMEOUT_MS = 15_000;
const OPENBAO_REQUEST_TIMEOUT_MS = 10_000;
const ENV_FILE_PERMISSION_OWNER_ONLY = 0o600;

const REPOSITORY_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const EMAIL_SMTP_SECRET_KEYS = [
  "SMTP_HOST",
  "SMTP_PORT",
  "SMTP_SECURE",
  "SMTP_USERNAME",
  "SMTP_PASSWORD",
  "SMTP_SENDER"
];

const OBJECT_STORAGE_SECRET_KEYS = [
  "OBJECT_STORAGE_PROVIDER",
  "OBJECT_STORAGE_ACCESS_KEY",
  "OBJECT_STORAGE_SECRET_KEY",
  "OBJECT_STORAGE_API_TOKEN",
  "OBJECT_STORAGE_REGION",
  "OBJECT_STORAGE_BUCKET",
  "OBJECT_STORAGE_ENDPOINT",
  "OBJECT_STORAGE_PUBLIC_BASE_URL",
  "OBJECT_STORAGE_FORCE_PATH_STYLE"
];

const AUTH_SIGNING_SECRET_KEYS = [
  "AUTH_JWT_SECRET",
  "OIDC_COOKIE_SECRET",
  "OIDC_JWKS_KEYS",
  "OIDC_ADMIN_CLIENT_SECRET",
  "OIDC_STORYBOOK_CLIENT_SECRET"
];

// be-prisma seed가 OIDC 클라이언트를 DB에 등록할 때 API와 동일 시크릿이 필요하다.
const OIDC_SEED_SECRET_KEYS = ["OIDC_ADMIN_CLIENT_SECRET", "OIDC_STORYBOOK_CLIENT_SECRET"];

const SECRET_PULL_SOURCES = [
  {
    kvPath: "core-api/development",
    envFiles: [
      {
        relativePath: "apps/core/api/.env",
        keys: [...EMAIL_SMTP_SECRET_KEYS, ...OBJECT_STORAGE_SECRET_KEYS, ...AUTH_SIGNING_SECRET_KEYS]
      },
      {
        relativePath: "packages/be-prisma/.env",
        keys: OIDC_SEED_SECRET_KEYS
      }
    ]
  },
  {
    kvPath: "idp-api/development",
    envFiles: [
      {
        relativePath: "apps/idp/api/.env",
        keys: [...EMAIL_SMTP_SECRET_KEYS, ...AUTH_SIGNING_SECRET_KEYS]
      }
    ]
  }
];

const GENERATED_FILE_HEADER = "# Generated by scripts/pull-local-secrets.mjs — do not commit";

class OpenBaoRequestError extends Error {
  constructor(failureKind, message) {
    super(message);
    this.name = "OpenBaoRequestError";
    this.failureKind = failureKind;
  }
}

function parseScriptArguments(argv) {
  return {
    isDryRun: argv.includes("--dry-run"),
    isQuiet: argv.includes("--quiet")
  };
}

function resolveOpenBaoToken() {
  const environmentToken = process.env.VAULT_TOKEN?.trim();
  if (environmentToken) {
    return { token: environmentToken, source: "VAULT_TOKEN" };
  }

  const vaultTokenFilePath = path.join(os.homedir(), ".vault-token");
  if (fs.existsSync(vaultTokenFilePath)) {
    const fileToken = fs.readFileSync(vaultTokenFilePath, "utf8").trim();
    if (fileToken) {
      return { token: fileToken, source: vaultTokenFilePath };
    }
  }

  return null;
}

function printLoginGuidance(address) {
  console.error("❌ OpenBao 토큰을 찾을 수 없습니다.");
  console.error("   다음 중 한 가지로 인증하세요:");
  console.error("   1) export VAULT_TOKEN=<개발자 읽기 전용 토큰>");
  console.error("      (토큰 발급: prj-openbao 저장소 scripts/create-token.sh)");
  console.error("   2) vault login — 토큰이 ~/.vault-token에 저장됩니다");
  console.error(`   연결 주소: export VAULT_ADDR=${address}`);
}

async function isReachableOpenBao(address) {
  try {
    // /v1/sys/health는 상태를 나타내는 HTTP 코드(200 활성, 429 standby, 503 sealed
    // 등)를 반환한다. 응답이 왔다는 것 자체가 OpenBao에 도달했다는 뜻이므로
    // 봉인(503)이어도 터널을 재사용한다 — 봉인 안내는 sealed 검사가 담당한다.
    await fetch(`${address.replace(/\/+$/, "")}/v1/sys/health`, {
      signal: AbortSignal.timeout(2_000)
    });
    return true;
  } catch {
    return false;
  }
}

async function waitForOpenBaoTunnelReady(address, timeoutMs) {
  const pollIntervalMs = 500;
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (await isReachableOpenBao(address)) {
      return true;
    }
    await new Promise((resolve) => setTimeout(resolve, pollIntervalMs));
  }
  return false;
}

// 봉인(sealed) 상태면 읽기가 전부 실패하므로 진입 전에 명확히 안내한다.
// 원격(Cloudflare) 주소는 HTML을 반환해 판별할 수 없으므로 로컬/터널 주소만 검사한다.
async function resolveOpenBaoSealedMessage(address) {
  if (!address.startsWith("http://127.0.0.1") && !address.startsWith("http://localhost")) {
    return null;
  }

  try {
    const response = await fetch(`${address.replace(/\/+$/, "")}/v1/sys/health`, {
      signal: AbortSignal.timeout(2_000)
    });
    const health = await response.json();
    if (health?.sealed) {
      return "   봉인 해제: kubectl exec -n openbao openbao-0 -- bao operator unseal <UNSEAL_KEY>";
    }
  } catch {
    // 상태 조회 실패는 기존 흐름의 오류 메시지에 맡긴다.
  }

  return null;
}

// kubectl port-forward를 detached로 띄워 클러스터 OpenBao를 localhost:8200에
// 연결한다. 터널은 이 스크립트 종료 후에도 유지되어 다음 pull이 재사용한다.
async function startKubectlPortForwardTunnel({ isQuiet }) {
  const kubectlCheck = spawnSync("kubectl", ["version", "--client=true"], { encoding: "utf8" });
  if (kubectlCheck.status !== 0) {
    return null;
  }

  if (!isQuiet) {
    console.log("↻ OpenBao 터널 연결 중: kubectl port-forward -n openbao svc/openbao 8200:8200");
  }
  const tunnelProcess = spawn(
    "kubectl",
    ["port-forward", "-n", OPENBAO_TUNNEL_NAMESPACE, OPENBAO_TUNNEL_TARGET, "8200:8200"],
    { detached: true, stdio: "ignore" }
  );
  tunnelProcess.unref();

  const isTunnelReady = await waitForOpenBaoTunnelReady(
    LOCAL_OPENBAO_ADDRESS,
    OPENBAO_TUNNEL_READY_TIMEOUT_MS
  );
  return isTunnelReady ? LOCAL_OPENBAO_ADDRESS : null;
}

// VAULT_ADDR 지정이 우선이다. 다만 구 도메인 등 죽은 주소가 남아 있으면
// 경고 후 probe 순서(기존 터널 재사용 → 자동 port-forward → 원격 fallback)로
// 진행한다. 미지정 시에도 같은 순서를 따른다.
async function resolveOpenBaoConnection({ isQuiet }) {
  const configuredAddress = process.env.VAULT_ADDR?.trim();
  if (configuredAddress) {
    if (await isReachableOpenBao(configuredAddress)) {
      return configuredAddress;
    }

    // 구 도메인 등 죽은 주소가 export되어 있으면 자동 탐색으로 진행한다.
    // pnpm start(--quiet)에서는 출력 없이 넘어간다.
    if (!isQuiet) {
      console.warn(
        `⚠️ VAULT_ADDR(${configuredAddress})에 연결할 수 없어 자동 탐색으로 진행합니다.`
      );
      console.warn("   구 도메인이 export되어 있다면 shell 설정에서 갱신하세요.");
    }
  }

  if (await isReachableOpenBao(LOCAL_OPENBAO_ADDRESS)) {
    return LOCAL_OPENBAO_ADDRESS;
  }

  const tunnelAddress = await startKubectlPortForwardTunnel({ isQuiet });
  if (tunnelAddress) {
    return tunnelAddress;
  }

  return REMOTE_OPENBAO_ADDRESS_FALLBACK;
}

// 정기 pull이 토큰을 계속 쓸 수 있도록 self-renew를 시도한다 (실패는 무시).
async function renewOpenBaoTokenBestEffort({ address, token }) {
  try {
    await fetch(`${address.replace(/\/+$/, "")}/v1/auth/token/renew-self`, {
      method: "POST",
      headers: { "X-Vault-Token": token },
      body: "{}",
      signal: AbortSignal.timeout(OPENBAO_REQUEST_TIMEOUT_MS)
    });
  } catch {
    // 갱신 실패는 pull 결과에 영향을 주지 않는다.
  }
}

async function fetchKvSecretEntries({ address, token, kvPath }) {
  const requestUrl = `${address.replace(/\/+$/, "")}/v1/${OPENBAO_KV_MOUNT}/data/${kvPath}`;

  let response;
  try {
    response = await fetch(requestUrl, {
      headers: { "X-Vault-Token": token },
      signal: AbortSignal.timeout(OPENBAO_REQUEST_TIMEOUT_MS)
    });
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    throw new OpenBaoRequestError("network", `OpenBao 연결 실패 (${requestUrl}): ${reason}`);
  }

  if (response.status === 404) {
    return null;
  }
  if (response.status === 403) {
    throw new OpenBaoRequestError(
      "auth",
      `토큰이 만료되었거나 권한이 없습니다 (secret/${kvPath}). vault login으로 갱신하세요.`
    );
  }
  if (!response.ok) {
    throw new OpenBaoRequestError("http", `OpenBao 응답 오류 (secret/${kvPath}): HTTP ${response.status}`);
  }

  const payload = await response.json();
  const secretEntries = payload?.data?.data;
  if (!secretEntries || typeof secretEntries !== "object" || Array.isArray(secretEntries)) {
    throw new OpenBaoRequestError("http", `OpenBao 응답 형식이 예상과 다릅니다 (secret/${kvPath})`);
  }
  return secretEntries;
}

// wt.js formatEnvValue와 동일한 quoting 규칙 (OIDC_JWKS_KEYS JSON 등 특수값 대응)
function formatEnvValue(value) {
  const text = String(value);
  if (/^[A-Za-z0-9_./:-]+$/.test(text)) {
    return text;
  }
  return `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

function parseEnvAssignmentKey(line) {
  const match = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=/);
  return match ? match[1] : null;
}

function mergeSecretEntriesIntoEnvFile({ envFilePath, secretEntries, keys, isDryRun }) {
  const fetchedKeys = keys.filter((key) => key in secretEntries);
  const missingKeys = keys.filter((key) => !(key in secretEntries));

  const existingContent = fs.existsSync(envFilePath) ? fs.readFileSync(envFilePath, "utf8") : null;

  if (existingContent === null) {
    const generatedLines = [
      GENERATED_FILE_HEADER,
      "",
      ...fetchedKeys.map((key) => `${key}=${formatEnvValue(secretEntries[key])}`)
    ];
    if (!isDryRun) {
      fs.mkdirSync(path.dirname(envFilePath), { recursive: true });
      fs.writeFileSync(envFilePath, `${generatedLines.join("\n")}\n`, "utf8");
      fs.chmodSync(envFilePath, ENV_FILE_PERMISSION_OWNER_ONLY);
    }
    return { replacedKeys: [], appendedKeys: fetchedKeys, missingKeys };
  }

  const contentLines = existingContent.split("\n");
  if (contentLines.length > 0 && contentLines[contentLines.length - 1] === "") {
    contentLines.pop();
  }

  const mergedLines = [];
  const alreadyWrittenKeys = new Set();
  for (const line of contentLines) {
    const assignedKey = parseEnvAssignmentKey(line);
    if (assignedKey && fetchedKeys.includes(assignedKey)) {
      if (alreadyWrittenKeys.has(assignedKey)) {
        continue;
      }
      mergedLines.push(`${assignedKey}=${formatEnvValue(secretEntries[assignedKey])}`);
      alreadyWrittenKeys.add(assignedKey);
      continue;
    }
    mergedLines.push(line);
  }

  const appendedKeys = fetchedKeys.filter((key) => !alreadyWrittenKeys.has(key));
  const replacedKeys = [...alreadyWrittenKeys];

  if (!isDryRun) {
    if (appendedKeys.length > 0) {
      if (mergedLines.length > 0) {
        mergedLines.push("");
      }
      for (const key of appendedKeys) {
        mergedLines.push(`${key}=${formatEnvValue(secretEntries[key])}`);
      }
    }
    fs.writeFileSync(envFilePath, `${mergedLines.join("\n")}\n`, "utf8");
  }

  return { replacedKeys, appendedKeys, missingKeys };
}

function describeMergeResult({ envFilePath, mergeResult, isQuiet }) {
  if (isQuiet && mergeResult.missingKeys.length === 0) {
    return;
  }
  const changes = [
    mergeResult.replacedKeys.length > 0 ? `교체 ${mergeResult.replacedKeys.length}` : null,
    mergeResult.appendedKeys.length > 0 ? `추가 ${mergeResult.appendedKeys.length}` : null
  ].filter(Boolean);
  const changeSummary = changes.length > 0 ? changes.join(", ") : "변경 없음";
  console.log(`  ✓ ${path.relative(REPOSITORY_ROOT, envFilePath)}: ${changeSummary}`);
  if (mergeResult.missingKeys.length > 0) {
    console.log(
      `    ⚠️ OpenBao에 없어 건드리지 않은 키: ${mergeResult.missingKeys.join(", ")}`
    );
  }
}

async function main() {
  const { isDryRun, isQuiet } = parseScriptArguments(process.argv.slice(2));
  const tokenInfo = resolveOpenBaoToken();

  if (!tokenInfo) {
    printLoginGuidance(LOCAL_OPENBAO_ADDRESS);
    process.exit(1);
  }

  const address = await resolveOpenBaoConnection({ isQuiet });

  const sealedMessage = await resolveOpenBaoSealedMessage(address);
  if (sealedMessage) {
    console.error("❌ OpenBao가 봉인(sealed) 상태여서 시크릿을 읽을 수 없습니다.");
    console.error(sealedMessage);
    process.exit(1);
  }

  if (!isQuiet) {
    const modeLabel = isDryRun ? " (dry-run)" : "";
    console.log(`🔑 OpenBao 시크릿 pull${modeLabel} — ${address}`);
  }

  let pulledSourceCount = 0;

  for (const source of SECRET_PULL_SOURCES) {
    let secretEntries;
    try {
      secretEntries = await fetchKvSecretEntries({ address, token: tokenInfo.token, kvPath: source.kvPath });
    } catch (error) {
      if (error instanceof OpenBaoRequestError) {
        console.error(`❌ ${error.message}`);
        if (error.failureKind === "auth") {
          process.exit(1);
        }
        console.error("   기존 .env 값으로 진행하려면 이 오류를 무시하고 계속할 수 있습니다.");
        process.exit(1);
      }
      throw error;
    }

    if (secretEntries === null) {
      console.warn(
        `⚠️ OpenBao에 아직 등록되지 않은 경로입니다: secret/${source.kvPath} (건너뜀)`
      );
      continue;
    }

    pulledSourceCount += 1;
    if (!isQuiet) {
      console.log(`· secret/${source.kvPath}`);
    }

    for (const envFile of source.envFiles) {
      const envFilePath = path.join(REPOSITORY_ROOT, envFile.relativePath);
      const mergeResult = mergeSecretEntriesIntoEnvFile({
        envFilePath,
        secretEntries,
        keys: envFile.keys,
        isDryRun
      });
      describeMergeResult({ envFilePath, mergeResult, isQuiet });
    }
  }

  if (pulledSourceCount === 0 && !isQuiet) {
    console.warn("⚠️ 가져온 시크릿 경로가 없습니다. OpenBao 관리자에게 development 경로 등록을 요청하세요.");
  }

  if (pulledSourceCount > 0) {
    await renewOpenBaoTokenBestEffort({ address, token: tokenInfo.token });
  }
}

main().catch((error) => {
  if (error instanceof SyntaxError && error.message.includes("is not valid JSON")) {
    // Cloudflare Access 등이 HTML 로그인 페이지를 반환한 경우 — JSON 파싱 전에
    // 원인(터널 실패로 원격 주소로 폴백)을 안내한다.
    console.error("❌ OpenBao 응답이 JSON이 아닙니다 (HTML 수신).");
    console.error("   openbao.onjitda.com은 Cloudflare Access 뒤에 있어 CLI 직접 접근이 불가합니다.");
    console.error("   kubectl port-forward 터널 실패가 원인일 가능성이 높습니다:");
    console.error("   1) 클러스터 연결 확인: kubectl get pod -n openbao openbao-0 (Running && Ready여야 함)");
    console.error("   2) OpenBao가 Sealed이면 봉인 해제 필요: kubectl exec -n openbao openbao-0 -- bao operator unseal <UNSEAL_KEY>");
    console.error("   3) 재시도: pnpm secrets:pull");
    process.exit(1);
  }

  console.error(`❌ 예기치 못한 오류: ${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
});
